import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';
import { DEFAULT_MENU, validateCatalog } from '../catalog.js';
import { cardHtml, esc, SECTION_GROUPS } from '../menu-view.js';
import { contactBarHtml } from '../contact-bar.js';
import { promotionsHtml } from '../promotions.js';
import { DEFAULT_SLIDES, validateSlides } from '../slides-config.js';
import { PHONE, DELIVERY_FEE, FREE_FROM, WORK_HOURS, ORDER_HOURS, CONTACTS } from '../site-settings.js';
import { I18N } from '../locales.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => readFile(root + path, 'utf8');
validateCatalog(DEFAULT_MENU);
validateSlides(DEFAULT_SLIDES);
await Promise.all(['app','admin'].map(name => build({
  absWorkingDir: root, entryPoints: [`${name}.js`], outfile: `${name}.bundle.js`,
  bundle: true, format: 'iife', target: ['es2020'], minify: true,
  banner: { js: '// Generated by npm run build. Edit source files, then rebuild.' }
})));
await build({absWorkingDir:root,entryPoints:['worker.js'],outfile:'cloudflare-worker.js',bundle:true,format:'esm',platform:'browser',target:['es2022'],banner:{js:'// Cloudflare Worker bundle. Generated by npm run build. No secrets included.'}});
const adminTemplate = await read('admin.html');
const hash = async path => createHash('sha256').update(await read(path)).digest('hex').slice(0,12);
const version = { app: await hash('app.bundle.js'), css: await hash('styles.css'), admin:await hash('admin.bundle.js'), adminCss:await hash('admin.css') };
await writeFile(root+'admin.html',adminTemplate.replace(/src="admin\.bundle\.js(?:\?v=[^"]*)?"/,`src="admin.bundle.js?v=${version.admin}"`).replace(/href="admin\.css(?:\?v=[^"]*)?"/,`href="admin.css?v=${version.adminCss}"`));
const layout = await read('templates/layout.html');
const names = {home:'Главная',sushi:'Суши',sets:'Сеты',promo:'Акции',extras:'Дополнения',contacts:'Контакты',reviews:'Отзывы'};
const files = {home:'index.html',sushi:'sushi.html',sets:'sets.html',promo:'promo.html',extras:'extras.html',contacts:'contacts.html',reviews:'reviews.html'};
function staticText(html) {
  const values = {time:'45–60 мин',hours:WORK_HOURS,phone:PHONE,fee:`${DELIVERY_FEE} ₴`,freeFrom:`${FREE_FROM} ₴`,orderHours:ORDER_HOURS};
  return html.replace(/(<([a-z][a-z0-9]*)\b[^>]*\bdata-i18n="([^"]+)"[^>]*>)[\s\S]*?(<\/\2>)/gi, (match,open,tag,key,close) => {
    const value = (key === 'addrValue' && CONTACTS.address) || (key === 'footerCity' && CONTACTS.city.ru) || I18N.ru[key];
    if (value == null) throw new Error(`Missing translation: ${key}`);
    const translated = value.replace(/\{(\w+)\}/g, (placeholder,key) => values[key] ?? placeholder);
    return open + esc(translated) + close;
  }).replace(/(<([a-z][a-z0-9]*)\b[^>]*\bdata-fill="([^"]+)"[^>]*>)[\s\S]*?(<\/\2>)/gi, (match,open,tag,key,close) => open + esc(values[key]) + close);
}
for (const [page,file] of Object.entries(files)) {
  let content = (await read(`templates/${page}.html`)).replace('{{slides}}',promotionsHtml(DEFAULT_MENU));
  for (const [id,groups] of Object.entries(SECTION_GROUPS)) {
    const html = groups.map(group => {
      const items = DEFAULT_MENU.filter(group.test);
      if (!items.length) return '';
      const heading = group.title ? `<h3 class="group-title">${esc(I18N.ru[group.title])}</h3>` : '';
      return `<div class="menu-block">${heading}<div class="grid">${items.map(item => cardHtml(item)).join('')}</div></div>`;
    }).join('');
    content = content.replace(`<div id="${id}"></div>`, `<div id="${id}">${html}</div>`);
  }
  if (page !== 'home' && content.includes('<h2 class="title"')) content = content.replace('<h2 class="title"','<h1 class="title"').replace('</h2>','</h1>');
  let html = layout.replace('{{main}}',content).replace('{{contactBar}}',contactBarHtml()).replace('{{pageClass}}',page==='home'?'home-page':'').replace('{{title}}',`${names[page]} · YANASUSHI`);
  html = staticText(html).replace(`href="${file}" data-i18n=`, `href="${file}" aria-current="page" data-i18n=`);
  html = html.replace('href="styles.css"',`href="styles.css?v=${version.css}"`).replace('src="app.bundle.js"',`src="app.bundle.js?v=${version.app}"`);
  await writeFile(root + file,html);
}
console.log('Built 7 static pages with embedded product cards and classic JS bundles.');
