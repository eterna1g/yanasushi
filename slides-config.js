export const SLIDE_THEMES = ['sage','peach','forest'];
export function validSlideImage(value) {
  if (typeof value !== 'string' || value.length > 750000) return false;
  if (/^assets\/(banners|menu)\/[a-z0-9-]+\.webp$/.test(value)) return true;
  if (/^data:image\/(jpeg|png|webp);base64,[A-Za-z0-9+/=]+$/.test(value)) return true;
  try {const url=new URL(value);return url.protocol==='https:' && !url.username && !url.password && !/\s/.test(value);} catch {return false;}
}
export function validSlideHref(value) {
  return typeof value==='string' && /^(index|sushi|sets|promo|extras|contacts)\.html(?:#[a-zA-Z0-9_-]+)?$/.test(value);
}
export function validateSlides(config) {
  if (!config || !Number.isInteger(config.intervalMs) || config.intervalMs<3000 || config.intervalMs>15000 || !Array.isArray(config.slides) || config.slides.length>20) throw new Error('Слайды: до 20 баннеров, интервал от 3 до 15 секунд.');
  const ids=new Set();
  const slides=config.slides.map(s=>{
    if (!s || typeof s.id!=='string' || !/^[a-z0-9-]{1,80}$/.test(s.id) || ids.has(s.id)) throw new Error('Некорректный или повторяющийся ID слайда.');
    ids.add(s.id);
    if (typeof s.enabled!=='boolean' || !SLIDE_THEMES.includes(s.theme) || !['product','delivery','custom'].includes(s.mode)) throw new Error('Проверьте видимость, фон и тип слайда.');
    if (!validSlideImage(s.image)) throw new Error('Укажите фото слайда: HTTPS, файл WebP из assets или загруженное изображение до 750 КБ.');
    if (!validSlideHref(s.href)) throw new Error('Ссылка должна вести на страницу сайта, например sets.html или sushi.html#product-phila.');
    if (typeof s.productId!=='string' || (s.productId && !/^[a-z0-9-]{1,80}$/.test(s.productId)) || (s.mode==='product' && !s.productId)) throw new Error('Выберите блюдо для слайда.');
    const next={id:s.id,enabled:s.enabled,theme:s.theme,mode:s.mode,image:s.image,href:s.href,productId:s.productId};
    for (const key of ['eyebrow','title','description','value','badge','cta']) {
      const v=s[key];
      if (!v || typeof v.ru!=='string' || typeof v.uk!=='string' || v.ru.length>600 || v.uk.length>600 || (['title','cta'].includes(key)&&!v.ru.trim())) throw new Error('Заполните заголовок и кнопку RU. Длина каждого текста — до 600 символов.');
      next[key]={ru:v.ru,uk:v.uk};
    }
    return next;
  });
  return {intervalMs:config.intervalMs,slides};
}
