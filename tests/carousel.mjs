import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { testServer } from './helpers/server.mjs';
import { DEFAULT_MENU } from '../catalog.js';
import { PROMOTION_INTERVAL } from '../promotions.js';
const server=await testServer();
const executablePath=process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined);
const browser=await chromium.launch({executablePath,args:['--no-sandbox']}).catch(async error=>{await server.close();throw error;});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route('https://fonts.googleapis.com/**',route=>route.abort());
  await context.route('https://fonts.gstatic.com/**',route=>route.abort());
  await context.route('https://yellow-term-d7c1.zubashenkoserhii.workers.dev/**',route=>route.fulfill({status:503,body:'offline'}));
  const page=await context.newPage();page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.clock.install();
  await page.goto(server.base+'index.html');
  const root=page.locator('[data-carousel]');
  await page.waitForFunction(()=>document.querySelector('[data-carousel]').dataset.playing==='true');
  assert.equal(await root.locator('.promo-slide').count(),6);
  assert.equal(await root.locator('.is-active').getAttribute('data-slide-id'),'sharing');
  assert.equal(await page.locator('.social-icon').count(),3);
  assert.equal(await page.locator('.contact-bar a:not([href])').count(),0);
  await page.clock.runFor(PROMOTION_INTERVAL+50);
  assert.equal(await root.getAttribute('data-active-index'),'1','Automatic advancement');
  await root.hover();
  const before=await root.getAttribute('data-active-index');
  await page.clock.runFor(PROMOTION_INTERVAL+50);
  assert.equal(await root.getAttribute('data-active-index'),before,'Hover pauses autoplay');
  await root.locator('[data-carousel-next]').click();
  assert.equal(await root.getAttribute('data-active-index'),'2');
  await root.locator('[data-carousel-dot="5"]').click();
  await page.keyboard.press('ArrowRight');
  assert.equal(await root.getAttribute('data-active-index'),'0','Wrap-around with keyboard');
  await root.locator('[data-carousel-dot="1"]').click();
  assert.equal(await root.locator('.is-active').getAttribute('data-slide-id'),'phila');
  assert.match(await root.locator('.is-active .promo-offer strong').textContent(),/256/);
  await page.mouse.move(1,1);
  await page.clock.runFor(PROMOTION_INTERVAL+50);
  assert.equal(await root.getAttribute('data-active-index'),'1','Keyboard focus pauses autoplay');
  await root.locator('[data-carousel-toggle]').click();
  assert.equal(await root.locator('[data-carousel-toggle]').getAttribute('aria-pressed'),'false');
  await page.locator('[data-lang=uk]').click();
  assert.match(await root.locator('.is-active .promo-title').textContent(),/Більше/);
  await page.locator('[data-lang=ru]').click();
  await root.locator('[data-carousel-dot="0"]').click();
  await page.evaluate(()=>document.activeElement.blur());
  await page.mouse.move(1,1);
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await page.waitForFunction(()=>document.querySelector('.promo-art').complete&&document.querySelector('.promo-art').naturalWidth>0);
  await page.screenshot({path:tmpdir()+'/yanasushi-home-slider-desktop.png',fullPage:true,animations:'disabled'});
  assert(await page.evaluate(()=>document.querySelector('#popular').getBoundingClientRect().top<900),'Home stays compact');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.clock.runFor(100);
  await page.waitForFunction(()=>document.querySelector('[data-carousel-toggle]').disabled);
  assert(await root.locator('[data-carousel-toggle]').isDisabled());
  const reducedIndex=await root.getAttribute('data-active-index');
  await page.clock.runFor(PROMOTION_INTERVAL*2);
  assert.equal(await root.getAttribute('data-active-index'),reducedIndex,'Reduced motion disables autoplay');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:tmpdir()+'/yanasushi-home-slider-mobile.png',fullPage:true,animations:'disabled'});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No mobile overflow');
  await root.locator('.carousel-stage').dispatchEvent('pointerdown',{pointerType:'touch',clientX:300,clientY:200});
  await root.locator('.carousel-stage').dispatchEvent('pointerup',{pointerType:'touch',clientX:100,clientY:205});
  assert.equal(await root.getAttribute('data-active-index'),'1','Swipe');
  assert.equal(await root.locator('.promo-slide:not(.is-active) a').evaluateAll(anchors=>anchors.every(a=>a.closest('[inert]'))),true);
  await page.clock.runFor(500);
  await root.locator('.is-active .promo-cta').click();
  await page.waitForURL(/sushi\.html#product-phila$/);
  assert.match(page.url(),/sushi\.html#product-phila$/);
  assert(await page.locator('#product-phila').isVisible());
  assert.deepEqual(errors,[]);
  await context.close();

  const live=await browser.newContext({viewport:{width:1280,height:900}});
  await live.route('https://fonts.googleapis.com/**',r=>r.abort());await live.route('https://fonts.gstatic.com/**',r=>r.abort());
  let liveMenu=DEFAULT_MENU.map(item=>item.id==='phila'?{...item,price:199}:item);
  await live.route('https://yellow-term-d7c1.zubashenkoserhii.workers.dev/**',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify(liveMenu)}));
  const livePage=await live.newPage();await livePage.goto(server.base+'index.html');
  await livePage.waitForFunction(()=>document.querySelector('[data-slide-id=phila] .promo-offer strong')?.textContent.includes('199'));
  liveMenu=DEFAULT_MENU.filter(item=>!['phila','set-start','dragon','set-party','set-veggie'].includes(item.id));
  await livePage.reload();
  await livePage.waitForFunction(()=>document.querySelectorAll('.promo-slide').length===1);
  assert(await livePage.locator('[data-carousel-toggle]').isDisabled());
  await live.close();

  const nojs=await browser.newContext({javaScriptEnabled:false});
  await nojs.route('https://fonts.googleapis.com/**',r=>r.abort());await nojs.route('https://fonts.gstatic.com/**',r=>r.abort());
  const nojsPage=await nojs.newPage();await nojsPage.goto(server.base+'index.html');
  assert(await nojsPage.locator('.promo-slide').first().isVisible());
  assert(await nojsPage.locator('.promo-slide').nth(1).isHidden());
  assert(await nojsPage.locator('.carousel-controls').isHidden());
  assert.equal(await nojsPage.locator('.card').count(),4);
  await nojs.close();
  console.log('Carousel PASS: automatic rotation, arrows, dots, keyboard, touch, hover/focus pause, reduced motion, RU/UA, real product links, current API prices, removed offers, static fallback, compact mobile/desktop layout');
} finally {await browser.close();await server.close();}
